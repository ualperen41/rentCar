export async function POST() {
  try {
    await connectDB();

    // Clear existing fleet and re-populate with fresh dataset
    const count = await Car.countDocuments();
    if (count > 0) {
      await Car.deleteMany({});
    }

    const inserted = await Car.insertMany(sampleCars);

    return NextResponse.json({
      success: true,
      message: `Başarıyla ${inserted.length} araç Türk Lirası fiyatlarıyla veritabanına eklendi.`,
      count: inserted.length,
    });
  } catch (error) {
    console.error("Seed Cars Error:", error);
    return NextResponse.json(
      { success: false, message: "Veritabanı seed işlemi başarısız oldu." },
      { status: 500 }
    );
  }
}

export async function GET() {
  return POST();
}
